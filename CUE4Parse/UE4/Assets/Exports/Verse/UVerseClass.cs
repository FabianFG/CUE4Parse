using CUE4Parse.UE4.Assets.Readers;
using CUE4Parse.UE4.Objects.UObject;
using Newtonsoft.Json;

namespace CUE4Parse.UE4.Assets.Exports.Verse;

public class UVerseClass : UClass
{
    public EVerseClassFlags SolClassFlags;

    public override void Deserialize(FAssetArchive Ar, long validPos)
    {
        base.Deserialize(Ar, validPos);
        SolClassFlags = (EVerseClassFlags)GetOrDefault<uint>(nameof(SolClassFlags));
    }

    protected internal override void WriteJson(JsonWriter writer, JsonSerializer serializer)
    {
        base.WriteJson(writer, serializer);
        writer.WritePropertyName(nameof(SolClassFlags));
        serializer.Serialize(writer, SolClassFlags);
    }
}

[JsonConverter(typeof(EnumConverter<EVerseClassFlags>))]
[Flags]
public enum EVerseClassFlags : uint
{
	VCLASS_None = 0x00000000u,
	VCLASS_NativeBound = 0x00000001u,
	VCLASS_UniversallyAccessible = 0x00000002u,   // The class is accessible from any Verse path, and is in a package with a public scope.
	VCLASS_Concrete = 0x00000004u,                // The class can be instantiated without explicitly setting any properties
	VCLASS_Module = 0x00000008u,                  // This class represents a Verse module
	VCLASS_UHTNative = 0x00000010u,               // This class was created by UHT
	VCLASS_Tuple = 0x00000020u,                   // This class represents a tuple
	VCLASS_EpicInternal = 0x00000040u,            // This class is epic_internal
	VCLASS_HasInstancedSemantics = 0x00000080u,   // This class is using explicit instanced reference semantics (backcompat)
	VCLASS_FinalSuper = 0x00000100u,              // This class has a <final_super> attribute
	VCLASS_Castable = 0x00000200u,                // This class has a <castable> attribute
	VCLASS_EpicInternalConstructor = 0x00000400u, // This class's constructor is epic_internal
	VCLASS_Persistable = 0x00000800u,             // This class has a <persistable> attribute
	VCLASS_Parametric = 0x00001000u,              // This class definition is local to a function, i.e. is parametric
	VCLASS_InternalCodegen = 0x00002000u,         // This class is generated by the compiler for internal purposes and not represent any user-defined class.
	VCLASS_PersonaConstructible = 0x00004000u,    // This class may be constructed by Persona
	VCLASS_HasVar = 0x00008000u,                  // This class has at least one mutable variable.  (Not needed in new VM)
	VCLASS_InheritsFromBlueprint = 0x00010000u,   // This class has a blueprint class as (transitive) superclass
	VCLASS_HasTransientSubobjects = 0x00020000u,  // This class has a non-serialized reference to an archetype instantiation
	VCLASS_HasFieldAttribute = 0x00040000u,       // This class or a superclass uses the @field attribute
	VCLASS_Deprecated = 0x00080000u,              // This class has the @deprecated attribute
	VCLASS_BPVerseDialect = 0x00100000u,          // This class was compiled with the BPVerse dialect (uLang::EVerseDialect::BPVerse)
	VCLASS_OverridesSceneEventOnReceive = 0x00200000u,      // This class or a superclass overrides component.OnReceive
	VCLASS_SceneEventOnReceiveClientRunnable = 0x00400000u, // Effective component.OnReceive is native, Epic-scope, <predicts>, or the default no-op
	VCLASS_EmptyBlock = 0x00800000u,              // This class has no block clause: its $Block function runs nothing

	VCLASS_Err_Inoperable = 0x40000000u, // One or more of the class's functions contain mis-linked (malformed) bytecode

	VCLASS_Err_Incomplete = 0x80000000u, // The class layout is malformed (missing super, illformed data-member, etc.)

	VCLASS_Err = (VCLASS_Err_Incomplete | VCLASS_Err_Inoperable)
}
