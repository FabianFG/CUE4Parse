{
    public byte[] Decrypt(byte[] ciphertext, ReadOnlyMemory<byte> key)
    {
        var decrypted = new byte[ciphertext.Length];

        DecryptSm4(key.Span[..16], ciphertext, decrypted);

        return decrypted;
    }

